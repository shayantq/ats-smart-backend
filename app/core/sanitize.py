"""
ابزار پاکسازی (Sanitize) ورودی‌های متنی کاربر.
هدف: حذف هر گونه تگ HTML/جاوااسکریپت پیش از رسیدن ورودی به لایه‌ی دیتابیس یا منطق تجاری،
تا در صورت نمایش بعدیِ همان متن در فرانت‌اند (مثلاً نام شرکت یا شرح آگهی شغلی)
هیچ کد مخربی اجرا نشود (XSS).

نکته: فیلدهایی مثل email که با EmailStr پردازش می‌شوند، به‌خودی‌خود توسط Pydantic
در برابر مقادیر ناهنجار محافظت می‌شوند. این ابزار برای فیلدهای متنی آزاد
(مثل نام، عنوان شغل، توضیحات) در این و آینده‌ی پروژه استفاده می‌شود.
"""

import re

_HTML_TAG_PATTERN = re.compile(r"<[^>]*>")


def strip_html_tags(value: str) -> str:
    """هر گونه تگ HTML (از جمله <script>) را از یک رشته حذف و فضای خالی اطراف را پاک می‌کند."""
    if not isinstance(value, str):
        return value
    return _HTML_TAG_PATTERN.sub("", value).strip()
